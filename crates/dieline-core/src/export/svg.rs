use super::layout::Page;
use super::{hex, LineKind};
use crate::geom::fmt;

/// SVG in millimetres with one Inkscape-style layer per line type.
/// Cricut Design Space and Brother CanvasWorkspace both import each group as a separate layer.
pub fn write(page: &Page, title: &str) -> String {
    let mut s = String::new();
    s.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    s.push_str(&format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" xmlns:inkscape=\"http://www.inkscape.org/namespaces/inkscape\" \
         width=\"{w}mm\" height=\"{h}mm\" viewBox=\"0 0 {w} {h}\">\n",
        w = fmt(page.w),
        h = fmt(page.h)
    ));
    s.push_str(&format!("<title>{}</title>\n", escape(title)));
    s.push_str("<desc>Generated by PackMate. Units: mm. Red = cut, blue = crease/score, magenta = perforation.</desc>\n");
    for kind in LineKind::ALL {
        let paths: Vec<_> = page.paths.iter().filter(|p| p.kind == kind).collect();
        if paths.is_empty() {
            continue;
        }
        let dash = if kind == LineKind::Crease {
            " stroke-dasharray=\"3 1.5\""
        } else {
            ""
        };
        s.push_str(&format!(
            "<g id=\"{id}\" inkscape:groupmode=\"layer\" inkscape:label=\"{label}\" fill=\"none\" stroke=\"{c}\" \
             stroke-width=\"0.25\" stroke-linecap=\"round\" stroke-linejoin=\"round\"{dash}>\n",
            id = kind.id(),
            label = kind.label(),
            c = hex(kind),
        ));
        // Crease layer as one compound path keeps the machine software's layer list short.
        if kind == LineKind::Cut {
            for p in paths {
                s.push_str(&format!("<path d=\"{}\"/>\n", p.svg_d()));
            }
        } else {
            let d: Vec<String> = paths.iter().map(|p| p.svg_d()).collect();
            s.push_str(&format!("<path d=\"{}\"/>\n", d.join(" ")));
        }
        s.push_str("</g>\n");
    }
    s.push_str("</svg>\n");
    s
}

fn escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}
